"""
scripts/null_out_title_only.py
------------------------------
Safe, selective NULL-out script for rows generated by title-only backfills.
Resets:
    analysis_status = 'pending'
    why_this_works = NULL
    used_for_note = NULL
    analysis_attempts = 0
    analysis_source = 'unknown'

DEFAULTS TO DRY-RUN. To execute live update, pass --apply flag.
"""

import os
import sys
import json
import argparse
import psycopg2
from dotenv import load_dotenv

load_dotenv("backend/.env")
load_dotenv(".env")

def main():
    parser = argparse.ArgumentParser(description="NULL-out title-only backfilled rows safely.")
    parser.add_argument("--apply", action="store_true", help="Execute live updates to DB (defaults to dry-run)")
    parser.add_argument("--ids-file", default="evidence/order93/title_only_ids.json", help="Path to JSON file containing target IDs")
    args = parser.parse_args()

    db_url = os.getenv("SUPABASE_DB_URL")
    if not db_url:
        print("Error: SUPABASE_DB_URL not found.")
        sys.exit(1)

    if not os.path.exists(args.ids_file):
        print(f"Error: IDs file {args.ids_file} does not exist.")
        sys.exit(1)

    with open(args.ids_file, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    # Use target zero_caption_ids or explicit id list
    target_ids = data.get("zero_caption_ids") or data.get("target_ids") or []
    print(f"Loaded {len(target_ids)} target IDs from {args.ids_file}")

    if not target_ids:
        print("No target IDs found to reset.")
        return

    conn = psycopg2.connect(db_url)
    cur = conn.cursor()

    # Dry-run count query
    cur.execute("""
    SELECT count(*),
           count(CASE WHEN why_this_works IS NOT NULL THEN 1 END) as with_text,
           count(CASE WHEN analysis_status = 'completed' THEN 1 END) as completed_status
    FROM trends
    WHERE id = ANY(%s);
    """, (target_ids,))
    total_match, with_text, completed_status = cur.fetchone()

    print("\n=== DRY RUN AUDIT ===")
    print(f"Target IDs submitted:     {len(target_ids)}")
    print(f"Actual rows matching DB:  {total_match}")
    print(f"Rows with non-null text:  {with_text}")
    print(f"Rows with 'completed':    {completed_status}")

    if not args.apply:
        print("\n[DRY RUN ONLY]: No database changes were made.")
        print("To apply this NULL-out reset, run: python scripts/null_out_title_only.py --apply")
        cur.close()
        conn.close()
        return

    print("\nExecuting LIVE reset...")
    cur.execute("""
    UPDATE trends
    SET why_this_works = NULL,
        used_for_note = NULL,
        analysis_status = 'pending',
        analysis_attempts = 0
    WHERE id = ANY(%s);
    """, (target_ids,))
    affected = cur.rowcount
    conn.commit()
    print(f"Successfully reset {affected} rows to pending (texts nulled, attempts reset to 0).")
    cur.close()
    conn.close()

if __name__ == "__main__":
    main()
